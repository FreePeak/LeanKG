#!/usr/bin/env python3
"""Clone each repo in repos.yaml with --depth 1 at the pinned ref.

Skips clones that already exist (idempotent), so re-running `make setup` is a
no-op after the first run. If the existing clone's HEAD doesn't match the
pinned ref, prints a warning so the user can `make clean && make setup` if a
re-pin is needed.
"""
from __future__ import annotations

import argparse
import json
import shutil
import subprocess
import sys
from pathlib import Path

try:
    import yaml
except ImportError:
    print("ERROR: PyYAML is required for clone_repos.py. Install with: pip install pyyaml", file=sys.stderr)
    sys.exit(2)


def parse_args(argv: list[str] | None = None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--repos", type=Path, help="Path to repos.yaml")
    parser.add_argument("--target", type=Path, help="Directory to clone into")
    parser.add_argument(
        "--lock-only",
        action="store_true",
        help="resolve every ref to a commit SHA and write repos.lock.yaml without cloning",
    )
    parser.add_argument("--selftest", action="store_true", help="offline checks on a local bare repo; no network")
    args = parser.parse_args(argv)
    if not args.selftest and (args.repos is None or args.target is None):
        parser.error("--repos and --target are required")
    return args


def write_lock(lock_path: Path, lock: dict[str, dict[str, str]]) -> None:
    lines = ["# Generated by clone_repos.py — do not edit.", "# Pinned corpus for benchmark reproducibility (FR-ZCP-08)."]
    for slug, info in lock.items():
        lines.append(f"{slug}:")
        lines.append(f"  url: {info['url']}")
        lines.append(f"  ref: {info['ref']}")
        lines.append(f"  sha: {info['sha']}")
        if "error" in info:
            lines.append(f"  error: {json.dumps(info['error'])}")
    lock_path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"  [lock] wrote {lock_path}")


def resolve_sha(url: str, ref: str) -> str:
    """FR-ZCP-08: resolve a ref (tag/branch) to its pinned 40-hex commit SHA.

    Movable refs (master, stable/*) drift — the lock file freezes the corpus
    so a re-run in three months indexes the same commit.
    """
    lines = subprocess.run(
        ["git", "ls-remote", url, ref, f"{ref}^{{}}"],
        check=True, capture_output=True, text=True,
    ).stdout.splitlines()
    # An annotated tag lists its tag-object SHA and a peeled `^{}` line for the
    # commit. A clone's HEAD is the commit, so prefer the peeled line.
    pairs = [line.split() for line in lines if line.strip()]
    peeled = [sha for sha, name in pairs if name.endswith("^{}")]
    plain = [sha for sha, name in pairs if not name.endswith("^{}")]
    sha = (peeled or plain or [""])[0]
    if len(sha) != 40:
        raise RuntimeError(f"could not resolve {ref} at {url}")
    return sha


def load_locked_shas(lock_path: Path) -> dict[str, str]:
    """slug -> 40-hex SHA from repos.lock.yaml; unresolved or missing entries are left out."""
    if not lock_path.is_file():
        return {}
    data = yaml.safe_load(lock_path.read_text(encoding="utf-8")) or {}
    return {slug: str(info["sha"]) for slug, info in data.items() if len(str(info.get("sha", ""))) == 40}


def checkout_locked(url: str, sha: str, target: Path) -> None:
    """Fetch exactly `sha` into a new clone at `target` and detach HEAD there."""
    target.mkdir(parents=True)
    _git("init", "-q", cwd=target)
    _git("remote", "add", "origin", url, cwd=target)
    try:
        _git("fetch", "-q", "--depth", "1", "origin", sha, cwd=target)
    except subprocess.CalledProcessError:
        # Server refused fetch-by-SHA: fall back to all refs (full history, slower).
        _git("fetch", "-q", "origin", cwd=target)
    try:
        _git("checkout", "-q", "--detach", sha, cwd=target)
    except subprocess.CalledProcessError as exc:
        raise RuntimeError(f"locked commit {sha[:10]} not found at {url}") from exc
    head = _git("rev-parse", "HEAD", cwd=target)
    if head != sha:
        raise RuntimeError(f"HEAD {head[:10]} != locked {sha[:10]} after checkout")


def git_clone_shallow(url: str, target: Path, sha: str) -> None:
    """Check out `sha` at `target`, reusing an existing clone only when its HEAD already matches."""
    if target.exists():
        try:
            head = _git("rev-parse", "HEAD", cwd=target)
        except subprocess.CalledProcessError:
            head = ""
        if head == sha:
            print(f"  [skip] {target.name} already at {sha[:10]}")
            return
        print(f"  [warn] {target.name} HEAD={head[:10]} != locked {sha[:10]}; re-cloning")
        shutil.rmtree(target)
    print(f"  [clone] {url} -> {target} @ {sha[:10]}")
    checkout_locked(url, sha, target)


def _git(*args: str, cwd: Path | None = None) -> str:
    return subprocess.run(["git", *args], cwd=cwd, check=True, capture_output=True, text=True).stdout.strip()


def _write_repos_yaml(path: Path, url: str, ref: str) -> None:
    path.write_text(f"repos:\n  - slug: demo\n    url: {url}\n    ref: {ref}\n", encoding="utf-8")


def selftest() -> int:
    """Offline: a local bare repo as origin; the lock pins the first commit while the branch tip is the second."""
    import tempfile

    with tempfile.TemporaryDirectory() as tmp:
        root = Path(tmp)
        work = root / "work"
        work.mkdir()
        _git("init", "-q", "-b", "main", cwd=work)
        ident = ["-c", "user.name=selftest", "-c", "user.email=selftest@example.invalid"]
        for name in ("a", "b"):
            (work / f"{name}.txt").write_text(name, encoding="utf-8")
            _git("add", ".", cwd=work)
            _git(*ident, "commit", "-q", "-m", name, cwd=work)
            if name == "a":
                first = _git("rev-parse", "HEAD", cwd=work)
        second = _git("rev-parse", "HEAD", cwd=work)
        origin = root / "origin.git"
        _git("clone", "-q", "--bare", str(work), str(origin))
        url = str(origin)
        repos_yaml = root / "repos.yaml"
        _write_repos_yaml(repos_yaml, url, "main")

        # Case 1: lock pins the first commit; setup must check out that SHA, not the tip.
        case1 = root / "pinned"
        case1.mkdir()
        write_lock(case1 / "repos.lock.yaml", {"demo": {"url": url, "ref": "main", "sha": first}})
        lock_before = (case1 / "repos.lock.yaml").read_bytes()
        rc = main(["--repos", str(repos_yaml), "--target", str(case1 / "repos")])
        assert rc == 0, f"setup at locked sha exited {rc}"
        head = _git("rev-parse", "HEAD", cwd=case1 / "repos" / "demo")
        assert head == first, f"HEAD {head[:10]} != locked {first[:10]} (tip is {second[:10]})"
        assert (case1 / "repos.lock.yaml").read_bytes() == lock_before, "plain setup rewrote the lock"

        # Case 2: lock pins a SHA the server does not have; setup must fail non-zero.
        case2 = root / "missing"
        case2.mkdir()
        write_lock(case2 / "repos.lock.yaml", {"demo": {"url": url, "ref": "main", "sha": "f" * 40}})
        rc = main(["--repos", str(repos_yaml), "--target", str(case2 / "repos")])
        assert rc != 0, "setup with an unreachable locked sha must exit non-zero"

        # Case 3: --lock-only on an unchanged remote reproduces the lock byte for byte.
        case3 = root / "lockonly"
        case3.mkdir()
        write_lock(case3 / "repos.lock.yaml", {"demo": {"url": url, "ref": "main", "sha": second}})
        lock_before = (case3 / "repos.lock.yaml").read_bytes()
        rc = main(["--repos", str(repos_yaml), "--target", str(case3 / "repos"), "--lock-only"])
        assert rc == 0 and (case3 / "repos.lock.yaml").read_bytes() == lock_before, "--lock-only changed the lock"

    print("clone_repos selftest: OK (locked sha checkout, unreachable sha fails, lock-only byte-identical)")
    return 0


def main(argv: list[str] | None = None) -> int:
    args = parse_args(argv)
    if args.selftest:
        return selftest()
    data = yaml.safe_load(args.repos.read_text(encoding="utf-8"))
    repos = data.get("repos", [])
    if not repos:
        print("ERROR: repos.yaml has no 'repos' list", file=sys.stderr)
        return 2
    args.target.mkdir(parents=True, exist_ok=True)
    lock_path = args.target.parent / "repos.lock.yaml"

    if args.lock_only:
        lock: dict[str, dict[str, str]] = {}
        unresolved = 0
        for entry in repos:
            info = {"url": entry["url"], "ref": entry["ref"]}
            try:
                info["sha"] = resolve_sha(entry["url"], entry["ref"])
            except (subprocess.CalledProcessError, RuntimeError) as exc:
                info.update(sha="UNRESOLVED", error=str(exc))
                unresolved += 1
            lock[entry["slug"]] = info
        write_lock(lock_path, lock)
        return 1 if unresolved else 0

    # FR-ZCP-08: setup checks out the locked SHA. The lock is never rewritten here;
    # only --lock-only does that. A repo with no lock entry is cloned at its ref's tip.
    locked = load_locked_shas(lock_path)
    failures: list[tuple[str, str]] = []
    for entry in repos:
        slug = entry["slug"]
        url = entry["url"]
        target = args.target / slug
        try:
            sha = locked.get(slug)
            if sha is None:
                sha = resolve_sha(url, entry["ref"])
                print(f"  [warn] {slug} has no lock entry; using {entry['ref']} at {sha[:10]} (run: make lock)")
            git_clone_shallow(url, target, sha)
        except (subprocess.CalledProcessError, RuntimeError) as exc:
            failures.append((slug, str(exc)))
            # Clean up partial clone so a retry is possible
            if target.exists():
                shutil.rmtree(target, ignore_errors=True)

    if failures:
        print("\nFAILED clones (continuing so other repos still get cloned):", file=sys.stderr)
        for slug, err in failures:
            print(f"  - {slug}: {err}", file=sys.stderr)
        return 1
    print(f"\ncloned {len(repos)} repos into {args.target}")
    return 0


if __name__ == "__main__":
    sys.exit(main())